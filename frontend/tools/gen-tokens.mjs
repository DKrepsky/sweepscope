// Generates src/design-system/tokens.generated.ts from tokens.css (ADR 0002). Zero dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const paths = {
  frontendCss: here('../src/design-system/tokens.css'),
  prototypeCss: here('../../docs/design-prototype/tokens.css'),
  generatedTs: here('../src/design-system/tokens.generated.ts'),
};

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');
// Prettier rewrites attribute quotes, so selectors are compared with double quotes.
const normaliseQuotes = (css) => css.replace(/\[data-theme='([\w-]+)'\]/g, '[data-theme="$1"]');
const stripAtRules = (css) => css.replace(/@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, '');
const collapse = (text) => text.replace(/\s+/g, ' ').trim();

function assertLiteral(name, value) {
  if (/var\(|calc\(|env\(/.test(value)) throw new Error(`Token ${name} is not a literal value: ${value}`);
  if (value === '') throw new Error(`Token ${name} has an empty value`);
}

function parseDeclarations(body) {
  const tokens = {};
  for (const declaration of body.split(';')) {
    const separator = declaration.indexOf(':');
    const name = collapse(declaration.slice(0, separator));
    if (separator < 0 || !name.startsWith('--ss-')) continue;
    const value = collapse(declaration.slice(separator + 1)).replaceAll("'", '"');
    assertLiteral(name, value);
    tokens[name.slice('--ss-'.length)] = value;
  }
  return tokens;
}

/** Tokens of every top-level block whose selector equals `selector`, merged in order. */
export function parseTokenBlock(css, selector) {
  const pattern = new RegExp(`(?:^|\\})\\s*${escapeRegExp(selector)}\\s*\\{([^{}]*)\\}`, 'g');
  const source = stripAtRules(normaliseQuotes(stripComments(css)));
  return [...source.matchAll(pattern)].reduce((all, match) => ({ ...all, ...parseDeclarations(match[1] ?? '') }), {});
}

export function parseThemeNames(css) {
  const source = stripAtRules(normaliseQuotes(stripComments(css)));
  return [...source.matchAll(/:root\[data-theme="([\w-]+)"\]\s*\{/g)].map((match) => match[1]);
}

/** Token overrides declared inside `@media (prefers-reduced-motion: reduce)`. */
export function parseReducedMotionTokens(css) {
  const media = stripComments(css).match(/@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{[^{}]*\{([^{}]*)\}\s*\}/);
  return parseDeclarations(media?.[1] ?? '');
}

const themeSelector = (theme) => `:root[data-theme="${theme}"]`;

function renderTheme(theme, tokens) {
  const lines = Object.entries(tokens).map(([name, value]) => `    '${name}': '${value}',`);
  return `  '${theme}': {\n${lines.join('\n')}\n  },`;
}

export function generate(css) {
  const themes = parseThemeNames(css);
  if (themes.length === 0) throw new Error('No :root[data-theme="..."] block found');
  const byTheme = Object.fromEntries(themes.map((theme) => [theme, parseTokenBlock(css, themeSelector(theme))]));
  const names = Object.keys(byTheme[themes[0]]);
  return [
    '// Generated by tools/gen-tokens.mjs from tokens.css. Do not edit.',
    `export const themes = {\n${themes.map((theme) => renderTheme(theme, byTheme[theme])).join('\n')}\n} as const;`,
    '',
    'export type ThemeName = keyof typeof themes;',
    `export type TokenName = ${names.map((name) => `'${name}'`).join(' | ')};`,
    `export const tokenNames: readonly TokenName[] = [${names.map((name) => `'${name}'`).join(', ')}];`,
    '',
  ].join('\n');
}

export function readTokenSources() {
  const read = (path) => readFileSync(path, 'utf8');
  return {
    frontendCss: read(paths.frontendCss),
    prototypeCss: read(paths.prototypeCss),
    generatedTs: read(paths.generatedTs),
  };
}

/** Returns the process exit code. `io` is injected so the failure path is testable. */
export function main(
  args,
  io = { read: (path) => readFileSync(path, 'utf8'), write: writeFileSync, error: console.error },
) {
  const input = args[0] ?? paths.frontendCss;
  const output = args[1] ?? paths.generatedTs;
  try {
    io.write(output, generate(io.read(input)));
    return 0;
  } catch (error) {
    io.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
