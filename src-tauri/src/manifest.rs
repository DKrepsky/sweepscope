use sweepscope_kernel::CommandDescriptor;

use crate::ipc::events::{CONNECTION_CHANGED, FACTS_CHANGED, INSTRUMENT_CHANGED, STATUS_CHANGED};

/// A slice event the shell forwards; `payload` is a TypeScript type expression.
pub struct EventDescriptor {
    pub name: &'static str,
    pub payload: &'static str,
    pub types: &'static [&'static str],
}

/// A binary stream and the commands that open and close it. They are not in `COMMANDS` because the
/// client calls them itself (`openStream`).
pub struct StreamDescriptor {
    pub kind: &'static str,
    pub open: &'static str,
    pub close: &'static str,
}

pub const EVENTS: &[EventDescriptor] = &[
    EventDescriptor {
        name: CONNECTION_CHANGED,
        payload: "ConnectionSnapshot",
        types: &["ConnectionSnapshot"],
    },
    EventDescriptor {
        name: INSTRUMENT_CHANGED,
        payload: "InstrumentState",
        types: &["InstrumentState"],
    },
    EventDescriptor {
        name: STATUS_CHANGED,
        payload: "AcquisitionStatus",
        types: &["AcquisitionStatus"],
    },
    EventDescriptor {
        name: FACTS_CHANGED,
        payload: "InstrumentFacts",
        types: &["InstrumentFacts"],
    },
];

pub const STREAMS: &[StreamDescriptor] = &[StreamDescriptor {
    kind: "frames",
    open: "open_frame_stream",
    close: "close_frame_stream",
}];

const GET_SNAPSHOT: CommandDescriptor = CommandDescriptor {
    name: "get_snapshot",
    args: "{}",
    result: "StateSnapshot",
    types: &["StateSnapshot"],
};

/// Every frontend-callable command of the app, in the order of `commands.ts`.
pub fn all_commands() -> Vec<CommandDescriptor> {
    [
        sweepscope_settings::COMMANDS,
        &[GET_SNAPSHOT],
        sweepscope_acquisition::COMMANDS,
        sweepscope_device::COMMANDS,
    ]
    .concat()
}

/// Renders `frontend/src/api/generated/commands.ts` from the manifest (ADR 0003), already in Prettier's layout.
pub fn render_commands_ts(commands: &[CommandDescriptor]) -> String {
    let mut out = String::from(
        "// Generated by the sweepscope-app export test from the Rust command manifest. Do not edit by hand.\n",
    );
    for name in imported_types(commands) {
        out.push_str(&format!("import type {{ {name} }} from './{name}';\n"));
    }
    out.push_str("\nexport const COMMANDS = [\n");
    for command in commands {
        out.push_str(&format!("  '{}',\n", command.name));
    }
    out.push_str("] as const;\nexport type CommandName = (typeof COMMANDS)[number];\n\n");
    out.push_str(&record(
        "CommandArgs",
        commands.iter().map(|c| (c.name, empty_as_record(c.args))),
    ));
    out.push('\n');
    out.push_str(&record("CommandResult", commands.iter().map(|c| (c.name, c.result))));
    out.push('\n');
    out.push_str(&render_events());
    out.push('\n');
    out.push_str(&render_streams());
    out
}

fn imported_types(commands: &[CommandDescriptor]) -> Vec<&'static str> {
    let mut types: Vec<&str> = commands.iter().flat_map(|c| c.types.iter().copied()).collect();
    types.extend(EVENTS.iter().flat_map(|e| e.types.iter().copied()));
    types.sort_unstable();
    types.dedup();
    types
}

fn empty_as_record(args: &'static str) -> &'static str {
    if args == "{}" {
        "Record<string, never>"
    } else {
        args
    }
}

fn record<'a>(type_name: &str, entries: impl Iterator<Item = (&'a str, &'a str)>) -> String {
    let mut out = format!("export type {type_name} = {{\n");
    for (name, value) in entries {
        out.push_str(&format!("  {name}: {value};\n"));
    }
    out.push_str("};\n");
    out
}

fn render_events() -> String {
    let names: Vec<String> = EVENTS.iter().map(|e| format!("'{}'", e.name)).collect();
    let mut out = format!("export const EVENTS = [{}] as const;\n", names.join(", "));
    out.push_str("export type EventName = (typeof EVENTS)[number];\n\n");
    out.push_str(&record("EventPayload", EVENTS.iter().map(|e| (e.name, e.payload))));
    out
}

fn render_streams() -> String {
    let kinds: Vec<String> = STREAMS.iter().map(|s| format!("'{}'", s.kind)).collect();
    let mut out = format!("export const STREAMS = [{}] as const;\n", kinds.join(", "));
    out.push_str("export type StreamKind = (typeof STREAMS)[number];\n");
    out
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;
    use crate::ipc::events;
    use crate::ipc::REGISTERED_COMMANDS;

    const GENERATED: &str = "../frontend/src/api/generated/commands.ts";

    fn generated_path() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join(GENERATED)
    }

    fn sorted(mut names: Vec<String>) -> Vec<String> {
        names.sort();
        names
    }

    fn manifest_names() -> Vec<String> {
        let mut names: Vec<String> = all_commands().iter().map(|c| c.name.to_owned()).collect();
        names.extend(STREAMS.iter().flat_map(|s| [s.open.to_owned(), s.close.to_owned()]));
        sorted(names)
    }

    fn registered_names() -> Vec<String> {
        sorted(REGISTERED_COMMANDS.iter().map(|name| (*name).to_owned()).collect())
    }

    /// Run with `UPDATE_GENERATED=1 cargo test -p sweepscope-app`, then `npx prettier --write` on the file.
    #[test]
    fn given_the_command_manifest_when_rendered_then_it_matches_the_committed_commands_ts() {
        let rendered = render_commands_ts(&all_commands());
        if std::env::var_os("UPDATE_GENERATED").is_some() {
            std::fs::write(generated_path(), &rendered).expect("write commands.ts");
        }
        let committed = std::fs::read_to_string(generated_path()).expect("read commands.ts");
        assert_eq!(committed, rendered);
    }

    #[test]
    fn given_the_manifest_and_the_registered_commands_when_compared_then_they_are_equal() {
        assert_eq!(manifest_names(), registered_names());
    }

    #[test]
    fn given_the_capability_when_read_then_it_allows_exactly_the_registered_commands() {
        let capability: serde_json::Value =
            serde_json::from_str(include_str!("../capabilities/main.json")).expect("capability json");
        let allowed = capability["permissions"]
            .as_array()
            .expect("permissions")
            .iter()
            .map(|p| p.as_str().expect("string").replace("allow-", "").replace('-', "_"))
            .collect();
        assert_eq!(sorted(allowed), registered_names());
    }

    #[test]
    fn given_the_build_script_when_read_then_it_lists_every_registered_command() {
        let build_script = include_str!("../build.rs");
        for name in registered_names() {
            assert!(
                build_script.contains(&format!("\"{name}\"")),
                "{name} is missing from build.rs"
            );
        }
        let listed = build_script.matches("    \"").count();
        assert_eq!(
            listed,
            registered_names().len(),
            "build.rs lists commands that are not registered"
        );
    }

    #[test]
    fn given_the_generated_permissions_when_listed_then_each_registered_command_has_one() {
        let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("permissions/autogenerated");
        let files = std::fs::read_dir(directory)
            .expect("permissions directory")
            .map(|entry| {
                let file = entry.expect("entry").file_name().to_string_lossy().into_owned();
                file.trim_end_matches(".toml").to_owned()
            })
            .collect();
        assert_eq!(sorted(files), registered_names());
    }

    #[test]
    fn given_the_event_manifest_when_compared_with_the_forwarders_then_the_names_are_equal() {
        let manifest: Vec<String> = EVENTS.iter().map(|e| e.name.to_owned()).collect();
        let forwarded = [
            events::CONNECTION_CHANGED,
            events::INSTRUMENT_CHANGED,
            events::STATUS_CHANGED,
            events::FACTS_CHANGED,
        ]
        .map(str::to_owned)
        .to_vec();
        assert_eq!(manifest, forwarded);
    }

    #[test]
    fn given_the_commands_without_arguments_when_rendered_then_they_take_an_empty_record() {
        let rendered = render_commands_ts(&all_commands());
        for name in ["get_snapshot", "force_trigger", "retry_connection"] {
            assert!(
                rendered.contains(&format!("  {name}: Record<string, never>;\n")),
                "{name}"
            );
        }
    }

    #[test]
    fn given_tauri_conf_when_parsed_then_window_minimum_and_csp_are_safe() {
        let conf: serde_json::Value =
            serde_json::from_str(include_str!("../tauri.conf.json")).expect("tauri.conf.json");
        let window = &conf["app"]["windows"][0];
        let csp = conf["app"]["security"]["csp"].as_str().expect("csp");
        assert_eq!(window["minWidth"], 1024);
        assert_eq!(window["minHeight"], 720);
        assert!(!csp.contains("unsafe-eval"));
        assert!(!csp.contains("https:"));
        assert_eq!(csp.matches("http:").count(), 1, "only the ipc.localhost origin");
    }
}
